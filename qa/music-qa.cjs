const {chromium}=require('playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'chrome',headless:true});try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 await page.goto('https://music-theory.aizcutei.com/post/%E5%BA%8F%E7%AF%87/1-%E4%BB%80%E4%B9%88%E6%98%AF%E9%9F%B3%E4%B9%90%E7%90%86%E8%AE%BA%EF%BC%9F',{waitUntil:'domcontentloaded',timeout:60000});
 await page.locator('svg[class*="style_icon"]').first().waitFor({timeout:30000});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.evaluate(()=>{window.values={preferences:{enabled:false}};window.listeners=[];window.chrome={storage:{local:{get:async()=>values},onChanged:{addListener:fn=>listeners.push(fn)}},runtime:{id:'test',onMessage:{addListener:()=>{}},sendMessage:async()=>{}}};});
 for(const file of ['content.css'])await page.addStyleTag({path:path.resolve(__dirname,'..',file)});
 for(const file of ['theme.js','lamp.js','content.js'])await page.addScriptTag({path:path.resolve(__dirname,'..',file)});
 await page.evaluate(()=>{values.preferences.enabled=true;for(const fn of listeners)fn({preferences:{newValue:values.preferences}},'local');});
 await page.waitForSelector('[data-pb-ui="lamp"]');
 await page.locator('[data-pb-ui="lamp"]').evaluate(el=>{for(const node of el.shadowRoot.querySelectorAll('*'))for(const a of node.getAnimations()){a.pause();a.currentTime=500;}});
 await page.screenshot({path:'qa/music-animation.png'});
 await page.waitForSelector('[data-pb-active]');
 await page.waitForSelector('[data-pb-ui="lamp"]',{state:'detached'});
 await page.screenshot({path:'qa/music-after.png'});
 const heading=page.locator('[id="3 关于规则的存在"]');
 await heading.scrollIntoViewIfNeeded();
 await page.evaluate(()=>window.dispatchEvent(new Event('resize')));
 await page.waitForTimeout(1000);
 assert.equal(await heading.evaluate(el=>getComputedStyle(el).color),'rgb(232, 232, 232)');
 assert.equal(await heading.evaluate(el=>getComputedStyle(el).webkitTextFillColor),'rgb(232, 232, 232)');
 await page.screenshot({path:'qa/music-heading.png'});
 const piano=page.locator('svg[class*="style_icon"]').first();
 assert.equal(await piano.evaluate(el=>getComputedStyle(el).filter),'invert(1)');
 const cat=page.locator('footer img').first();
 assert.match(await cat.evaluate(image=>getComputedStyle(image).filter),/drop-shadow/);
 await page.locator('footer').scrollIntoViewIfNeeded();
 await page.screenshot({path:'qa/music-footer.png'});
 await page.evaluate(()=>{values.preferences.enabled=false;for(const fn of listeners)fn({preferences:{newValue:values.preferences}},'local');});
 await page.waitForFunction(()=>!document.documentElement.hasAttribute('data-pb-active'));
 assert.equal(await piano.evaluate(el=>getComputedStyle(el).filter),'none');
 assert.equal(await cat.evaluate(el=>getComputedStyle(el).filter),'none');
 console.log('PASS: music-theory real page lamp under reduced-motion setting, dark piano icon visible, filter restored on disable.');
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
